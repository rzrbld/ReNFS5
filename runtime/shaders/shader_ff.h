/*
 * shader_ff.h - GLSL ES 1.00 sources for the Direct3D7 fixed-function
 * emulation. Included by runtime/render/renderer.c; kept in its own file so
 * the shaders can be reviewed (and diffed against D3D7 semantics) separate
 * from the state cache.
 *
 * Two vertex shaders:
 *   FF_VS_TL   - D3DTLVERTEX (XYZRHW): screen-space, exact D3D7 viewport/z
 *                convention, fog factor from the specular alpha (THRASH writes
 *                it there) and texture transforms.
 *   FF_VS_LIT  - XYZ vertices: world*view*projection with the D3D z range
 *                [0,1] remapped to GL's [-1,1]; optional fixed-function
 *                lighting (up to 8 lights, D3DLIGHT7 parameters) and
 *                per-vertex/table fog.
 * One fragment shader implements the D3D7 texture-stage cascade for up to two
 * stages (color + alpha ops/args), alpha test, colour key, texture factor,
 * specular add and fog.
 *
 * Orientation: the FBO is rendered with screen y=0 at GL y=-1 (bottom row),
 * so glReadPixels row 0 is screen row 0 and textures uploaded in guest row
 * order sample with D3D's v directly - no flips anywhere.
 */
#ifndef NFS5_SHADER_FF_H
#define NFS5_SHADER_FF_H

static const char FF_VS_TL[] =
    "#version 100\n"
    "precision highp float;\n"
    "attribute vec4 a_pos;\n"          /* sx, sy, sz, rhw */
    "attribute vec4 a_color;\n"        /* D3DCOLOR diffuse as normalized bytes B,G,R,A */
    "attribute vec4 a_spec;\n"         /* D3DCOLOR specular, same packing (a = TL fog factor) */
    "attribute vec2 a_tex0;\n"
    "attribute vec2 a_tex1;\n"
    "uniform vec4 u_viewport;\n"       /* x, y, w, h */
    "uniform mat4 u_texmat0;\n"
    "uniform mat4 u_texmat1;\n"
    "uniform int u_texgen;\n"          /* bit0/1: apply texture matrix 0/1 */
    "uniform int u_fog;\n"
    "uniform int u_fogvertex;\n"       /* 1: fog factor is the specular alpha (vertex fog) */
    "uniform int u_fogmode;\n"         /* 1 exp, 2 exp2, 3 linear */
    "uniform float u_fogstart;\n"
    "uniform float u_fogend;\n"
    "uniform float u_fogdensity;\n"
    "uniform int u_persp;\n"          /* 1: clip w = 1/rhw (D3D perspective-correct) */
    "varying vec4 v_color;\n"
    "varying vec4 v_spec;\n"
    "varying vec2 v_tex0;\n"
    "varying vec2 v_tex1;\n"
    "varying float v_fog;\n"
    "void main() {\n"
    "  float w = u_viewport.z > 0.5 ? u_viewport.z : 1.0;\n"
    "  float h = u_viewport.w > 0.5 ? u_viewport.w : 1.0;\n"
    "  float cw = (u_persp != 0 && a_pos.w > 1e-30) ? 1.0 / a_pos.w : 1.0;\n"
    "  gl_Position = vec4((a_pos.x - u_viewport.x) * 2.0 / w - 1.0,\n"
    "                     (a_pos.y - u_viewport.y) * 2.0 / h - 1.0,\n"
    "                     a_pos.z * 2.0 - 1.0, 1.0) * cw;\n"
    "  v_color = a_color.zyxw;\n"
    "  v_spec = a_spec.zyxw;\n"
    "  v_tex0 = a_tex0;\n"
    "  v_tex1 = a_tex1;\n"
    "  if (u_texgen == 1 || u_texgen == 3) v_tex0 = (u_texmat0 * vec4(a_tex0, 0.0, 1.0)).xy;\n"
    "  if (u_texgen >= 2) v_tex1 = (u_texmat1 * vec4(a_tex1, 0.0, 1.0)).xy;\n"
    "  float fog = 1.0;\n"
    "  if (u_fog != 0) {\n"
    "    if (u_fogvertex != 0) {\n"
    "      fog = a_spec.a;\n"
    "    } else {\n"
    /* Table fog on pre-transformed vertices: D3D computes the fog factor from
     * the vertex's eye-space depth, which for XYZRHW is w = 1/rhw. |
     */
    "      float d = 1.0 / max(a_pos.w, 1e-6);\n"
    "      if (u_fogmode == 3) fog = clamp((u_fogend - d) / max(u_fogend - u_fogstart, 0.0001), 0.0, 1.0);\n"
    "      else if (u_fogmode == 1) fog = clamp(exp(-u_fogdensity * d), 0.0, 1.0);\n"
    "      else fog = clamp(exp(-u_fogdensity * u_fogdensity * d * d), 0.0, 1.0);\n"
    "    }\n"
    "  }\n"
    "  v_fog = fog;\n"
    "}\n";

static const char FF_VS_LIT[] =
    "#version 100\n"
    "precision highp float;\n"
    "attribute vec3 a_pos;\n"
    "attribute vec3 a_normal;\n"
    "attribute vec4 a_color;\n"
    "attribute vec4 a_spec;\n"
    "attribute vec2 a_tex0;\n"
    "attribute vec2 a_tex1;\n"
    "uniform mat4 u_world;\n"
    "uniform mat4 u_view;\n"
    "uniform mat4 u_proj;\n"
    "uniform mat4 u_texmat0;\n"
    "uniform mat4 u_texmat1;\n"
    "uniform int u_texgen;\n"
    "uniform int u_lighting;\n"
    "uniform int u_fog;\n"
    "uniform int u_fogmode;\n"          /* 1 exp, 2 exp2, 3 linear */
    "uniform float u_fogstart;\n"
    "uniform float u_fogend;\n"
    "uniform float u_fogdensity;\n"
    "uniform vec4 u_mat_diffuse;\n"
    "uniform vec4 u_mat_ambient;\n"
    "uniform vec4 u_mat_specular;\n"
    "uniform vec4 u_mat_emissive;\n"
    "uniform vec4 u_ambient;\n"
    "uniform int u_light_count;\n"
    "uniform vec4 u_light_diffuse[8];\n"
    "uniform vec4 u_light_specular[8];\n"
    "uniform vec4 u_light_ambient[8];\n"
    "uniform vec4 u_light_pos[8];\n"    /* world-space position or direction */
    "uniform vec4 u_light_param[8];\n"  /* x=type, y=range, z=falloff */
    "varying vec4 v_color;\n"
    "varying vec4 v_spec;\n"
    "varying vec2 v_tex0;\n"
    "varying vec2 v_tex1;\n"
    "varying float v_fog;\n"
    "void main() {\n"
    "  vec4 wp = u_world * vec4(a_pos, 1.0);\n"
    "  vec4 vp = u_view * wp;\n"
    "  vec4 cp = u_proj * vp;\n"
    "  gl_Position = vec4(cp.x, cp.y, cp.z * 2.0 - cp.w, cp.w);\n"
    "  v_tex0 = a_tex0;\n"
    "  v_tex1 = a_tex1;\n"
    "  if (u_texgen == 1 || u_texgen == 3) v_tex0 = (u_texmat0 * vec4(a_tex0, 0.0, 1.0)).xy;\n"
    "  if (u_texgen >= 2) v_tex1 = (u_texmat1 * vec4(a_tex1, 0.0, 1.0)).xy;\n"
    "  if (u_lighting != 0) {\n"
    "    mat3 nmat = mat3(u_world[0].xyz, u_world[1].xyz, u_world[2].xyz);\n"
    "    vec3 n = nmat * a_normal;\n"
    "    float nlen = length(n);\n"
    "    n = nlen > 0.0001 ? n / nlen : vec3(0.0, 0.0, 1.0);\n"
    "    vec3 eye = normalize(-vp.xyz);\n"
    "    vec3 c = u_mat_emissive.rgb + u_mat_ambient.rgb * u_ambient.rgb;\n"
    "    vec3 s = vec3(0.0);\n"
    "    for (int i = 0; i < 8; i++) {\n"
    "      if (i >= u_light_count) break;\n"
    "      int type = int(u_light_param[i].x + 0.5);\n"
    "      vec3 L;\n"
    "      float atten = 1.0;\n"
    "      if (type == 3) {\n"
    "        L = normalize(-u_light_pos[i].xyz);\n"
    "      } else {\n"
    "        vec3 d = u_light_pos[i].xyz - wp.xyz;\n"
    "        float dist = length(d);\n"
    "        L = d / max(dist, 0.0001);\n"
    "        float range = u_light_param[i].y;\n"
    "        float falloff = u_light_param[i].z;\n"
    "        atten = 1.0 / (1.0 + dist * dist * 0.001) * falloff;\n"
    "        if (range > 0.0 && dist > range) atten = 0.0;\n"
    "      }\n"
    "      float ndl = max(dot(n, L), 0.0);\n"
    "      c += atten * ndl * u_light_diffuse[i].rgb * u_mat_diffuse.rgb;\n"
    "      vec3 H = normalize(L + eye);\n"
    "      float spec = pow(max(dot(n, H), 0.0), max(u_mat_specular.a, 1.0));\n"
    "      s += atten * spec * u_light_specular[i].rgb * u_mat_specular.rgb;\n"
    "    }\n"
    "    v_color = vec4(clamp(c, 0.0, 1.0), u_mat_diffuse.a);\n"
    "    v_spec = vec4(clamp(s, 0.0, 1.0), 1.0);\n"
    "  } else {\n"
    "    v_color = a_color;\n"
    "    v_spec = a_spec;\n"
    "  }\n"
    "  float fog = 1.0;\n"
    "  if (u_fog != 0) {\n"
    "    float d = length(vp.xyz);\n"
    "    if (u_fogmode == 3) fog = clamp((u_fogend - d) / max(u_fogend - u_fogstart, 0.0001), 0.0, 1.0);\n"
    "    else if (u_fogmode == 1) fog = clamp(exp(-u_fogdensity * d), 0.0, 1.0);\n"
    "    else fog = clamp(exp(-u_fogdensity * u_fogdensity * d * d), 0.0, 1.0);\n"
    "  }\n"
    "  v_fog = fog;\n"
    "}\n";

static const char FF_FS[] =
    "#version 100\n"
    "precision mediump float;\n"
    "varying vec4 v_color;\n"
    "varying vec4 v_spec;\n"
    "varying vec2 v_tex0;\n"
    "varying vec2 v_tex1;\n"
    "varying float v_fog;\n"
    "uniform sampler2D u_tex0;\n"
    "uniform sampler2D u_tex1;\n"
    "uniform int u_stage0_on;\n"
    "uniform int u_stage1_on;\n"
    "uniform int u_c0op, u_c0a1, u_c0a2, u_a0op, u_a0a1, u_a0a2;\n"
    "uniform int u_c1op, u_c1a1, u_c1a2, u_a1op, u_a1a1, u_a1a2;\n"
    "uniform vec4 u_tfactor;\n"
    "uniform int u_alpha_test, u_alpha_func;\n"
    "uniform float u_alpha_ref;\n"
    "uniform int u_colorkey_on;\n"
    "uniform vec4 u_colorkey_lo;\n"
    "uniform vec4 u_colorkey_hi;\n"
    "uniform int u_fog_on;\n"
    "uniform vec4 u_fog_color;\n"
    "uniform int u_specular_add;\n"
    "uniform int u_flat_diffuse;\n"      /* 1: ignore vertex diffuse, use uniform */
    "uniform vec4 u_flat_color;\n"
    "vec4 arg_value(int sel, vec4 texel, vec4 cur, vec4 diff, vec4 spec, vec4 tf) {\n"
    "  vec4 v;\n"
    "  int s = sel - (sel / 16) * 16;\n"
    "  if (s == 0) v = diff;\n"
    "  else if (s == 1) v = cur;\n"
    "  else if (s == 2) v = texel;\n"
    "  else if (s == 3) v = tf;\n"
    "  else if (s == 4) v = spec;\n"
    "  else v = diff;\n"
    "  int h = sel / 16; int comp = h - (h / 2) * 2;\n"
    "  int h2 = sel / 32; int arep = h2 - (h2 / 2) * 2;\n"
    "  if (comp != 0) v = vec4(1.0, 1.0, 1.0, 1.0) - v;\n"
    "  if (arep != 0) v.rgb = v.aaa;\n"
    "  return v;\n"
    "}\n"
    "vec4 combine_rgb(vec4 cur, vec4 texel, int op, int a1, int a2, vec4 diff, vec4 spec, vec4 tf) {\n"
    "  vec4 x = arg_value(a1, texel, cur, diff, spec, tf);\n"
    "  vec4 y = arg_value(a2, texel, cur, diff, spec, tf);\n"
    "  vec4 r = cur;\n"
    "  if (op == 2) r.rgb = x.rgb;\n"
    "  else if (op == 3) r.rgb = y.rgb;\n"
    "  else if (op == 4) r.rgb = x.rgb * y.rgb;\n"
    "  else if (op == 5) r.rgb = min(x.rgb * y.rgb * 2.0, vec3(1.0));\n"
    "  else if (op == 6) r.rgb = min(x.rgb * y.rgb * 4.0, vec3(1.0));\n"
    "  else if (op == 7) r.rgb = min(x.rgb + y.rgb, vec3(1.0));\n"
    "  else if (op == 8) r.rgb = clamp(x.rgb + y.rgb - 0.5, 0.0, 1.0);\n"
    "  else if (op == 9) r.rgb = clamp((x.rgb + y.rgb - 0.5) * 2.0, 0.0, 1.0);\n"
    "  else if (op == 10) r.rgb = clamp(x.rgb - y.rgb, 0.0, 1.0);\n"
    "  else if (op == 11) r.rgb = clamp(x.rgb + y.rgb - x.rgb * y.rgb, 0.0, 1.0);\n"
    "  else if (op == 12) r.rgb = mix(y.rgb, x.rgb, diff.a);\n"
    "  else if (op == 13) r.rgb = mix(y.rgb, x.rgb, texel.a);\n"
    "  else if (op == 14) r.rgb = mix(y.rgb, x.rgb, tf.a);\n"
    "  else if (op == 16) r.rgb = mix(y.rgb, x.rgb, cur.a);\n"
    "  else r.rgb = x.rgb * y.rgb;\n"
    "  return r;\n"
    "}\n"
    "vec4 combine_a(vec4 cur, vec4 texel, int op, int a1, int a2, vec4 diff, vec4 spec, vec4 tf) {\n"
    "  vec4 x = arg_value(a1, texel, cur, diff, spec, tf);\n"
    "  vec4 y = arg_value(a2, texel, cur, diff, spec, tf);\n"
    "  vec4 r = cur;\n"
    "  if (op == 2) r.a = x.a;\n"
    "  else if (op == 3) r.a = y.a;\n"
    "  else if (op == 4) r.a = x.a * y.a;\n"
    "  else if (op == 5) r.a = min(x.a * y.a * 2.0, 1.0);\n"
    "  else if (op == 6) r.a = min(x.a * y.a * 4.0, 1.0);\n"
    "  else if (op == 7) r.a = min(x.a + y.a, 1.0);\n"
    "  else if (op == 8) r.a = clamp(x.a + y.a - 0.5, 0.0, 1.0);\n"
    "  else if (op == 9) r.a = clamp((x.a + y.a - 0.5) * 2.0, 0.0, 1.0);\n"
    "  else if (op == 10) r.a = clamp(x.a - y.a, 0.0, 1.0);\n"
    "  else if (op == 11) r.a = clamp(x.a + y.a - x.a * y.a, 0.0, 1.0);\n"
    "  else if (op == 12) r.a = mix(y.a, x.a, diff.a);\n"
    "  else if (op == 13) r.a = mix(y.a, x.a, texel.a);\n"
    "  else if (op == 14) r.a = mix(y.a, x.a, tf.a);\n"
    "  else if (op == 16) r.a = mix(y.a, x.a, cur.a);\n"
    "  else r.a = x.a * y.a;\n"
    "  return r;\n"
    "}\n"
    "bool alpha_test_pass(float a) {\n"
    "  if (u_alpha_func == 1) return false;\n"
    "  if (u_alpha_func == 2) return a < u_alpha_ref;\n"
    "  if (u_alpha_func == 3) return abs(a - u_alpha_ref) < 0.002;\n"
    "  if (u_alpha_func == 4) return a <= u_alpha_ref;\n"
    "  if (u_alpha_func == 5) return a > u_alpha_ref;\n"
    "  if (u_alpha_func == 6) return abs(a - u_alpha_ref) >= 0.002;\n"
    "  if (u_alpha_func == 7) return a >= u_alpha_ref;\n"
    "  return true;\n"
    "}\n"
    "void main() {\n"
    "  vec4 tex0 = texture2D(u_tex0, v_tex0);\n"
    "  vec4 tex1 = texture2D(u_tex1, v_tex1);\n"
    "  vec4 diff = u_flat_diffuse != 0 ? u_flat_color : v_color;\n"
    "  vec4 cur = diff;\n"
    "  if (u_stage0_on != 0) {\n"
    "    cur = combine_rgb(cur, tex0, u_c0op, u_c0a1, u_c0a2, diff, v_spec, u_tfactor);\n"
    "    cur = combine_a(cur, tex0, u_a0op, u_a0a1, u_a0a2, diff, v_spec, u_tfactor);\n"
    "    if (u_colorkey_on != 0) {\n"
    "      if (tex0.r >= u_colorkey_lo.r && tex0.r <= u_colorkey_hi.r &&\n"
    "          tex0.g >= u_colorkey_lo.g && tex0.g <= u_colorkey_hi.g &&\n"
    "          tex0.b >= u_colorkey_lo.b && tex0.b <= u_colorkey_hi.b) cur.a = 0.0;\n"
    "    }\n"
    "  }\n"
    "  if (u_stage1_on != 0 && u_c1op != 1) {\n"
    "    cur = combine_rgb(cur, tex1, u_c1op, u_c1a1, u_c1a2, diff, v_spec, u_tfactor);\n"
    "    cur = combine_a(cur, tex1, u_a1op, u_a1a1, u_a1a2, diff, v_spec, u_tfactor);\n"
    "  }\n"
    "  if (u_specular_add != 0) cur.rgb = clamp(cur.rgb + v_spec.rgb, 0.0, 1.0);\n"
    "  if (u_alpha_test != 0 && !alpha_test_pass(cur.a)) discard;\n"
    "  if (u_fog_on != 0) cur.rgb = mix(u_fog_color.rgb, cur.rgb, clamp(v_fog, 0.0, 1.0));\n"
    "  gl_FragColor = vec4(cur.rgb, cur.a);\n"
    "}\n";

#endif /* NFS5_SHADER_FF_H */
