#!/usr/bin/env bash
# Prepare the public aarch64 cross toolchain and link inputs for the NFS5 port.
#
#   bash scripts/cross_prepare.sh            # build image if missing, then SDK
#   FORCE_IMAGE=1 bash scripts/cross_prepare.sh
#
# Produces (all generated, none of it is packaged for users):
#   third_party/target-libs/include/SDL2/   arm64 SDL2 headers
#   third_party/target-libs/lib/            link-time libSDL2 / libSDL2_ttf
#   third_party/target-libs/mali-link/      link-only GLES/EGL ABI stubs whose
#                                           SONAME is libmali.so.0 (the device
#                                           firmware supplies the real driver)
#   third_party/target-libs/SHA256SUMS
#
# The arm64 packages only provide public headers and link-time .so files. No
# firmware library is copied from a device and no libmali/libGLESv2 binary is
# ever shipped in the port package.
set -euo pipefail
cd "$(dirname "$0")/.."

image=${CROSS_IMAGE:-nfs5-cross:bookworm}
docker_bin=${DOCKER:-docker}
export DOCKER_CONFIG=${DOCKER_CONFIG:-$PWD/work/docker-config}
mkdir -p "$DOCKER_CONFIG"

if [[ ${FORCE_IMAGE:-0} == 1 ]] || ! "$docker_bin" image inspect "$image" >/dev/null 2>&1; then
    echo "Building cross image $image (network required)..." >&2
    "$docker_bin" build -f packaging/Dockerfile.cross -t "$image" packaging
fi

out=$PWD/third_party/target-libs
rm -rf "$out/include" "$out/lib" "$out/mali-link"
mkdir -p "$out/include/SDL2" "$out/lib" "$out/mali-link"
mkdir -p build
stage=$PWD/build/cross-prepare.$$
mkdir -p "$stage"
trap 'rm -rf -- "${stage:-/nonexistent}"' EXIT
cat > "$stage/prepare.sh" <<'CONTAINER_EOF'
set -eu
out=/out
mkdir -p "$out/include/SDL2" "$out/lib" "$out/mali-link"
# Public SDL2 headers (zlib license) for arm64, including the multiarch
# _real_SDL_config.h that the wrapper SDL_config.h includes.
cp -a /usr/include/SDL2/. "$out/include/SDL2/"
cp -aL /usr/include/aarch64-linux-gnu/SDL2/. "$out/include/SDL2/"
# Link-time only: the firmware provides libSDL2-2.0.so.0 at runtime.
cp -L /usr/lib/aarch64-linux-gnu/libSDL2.so "$out/lib/libSDL2.so"
cp -L /usr/lib/aarch64-linux-gnu/libSDL2_ttf.so "$out/lib/libSDL2_ttf.so"

# Link-only GLES/EGL ABI stubs. They export the public entry points but their
# SONAME is libmali.so.0, so the linked binary asks the firmware for the Mali
# driver. They are never packaged or executed by us.
aarch64-linux-gnu-nm -D --defined-only /usr/lib/aarch64-linux-gnu/libGLESv2.so |
    awk '$2 == "T" && $3 ~ /^gl[A-Z][A-Za-z0-9_]*$/ {print $3}' | sort -u > "$out/mali-link/gles-symbols.txt"
aarch64-linux-gnu-nm -D --defined-only /usr/lib/aarch64-linux-gnu/libEGL.so |
    awk '$2 == "T" && $3 ~ /^egl[A-Z][A-Za-z0-9_]*$/ {print $3}' | sort -u > "$out/mali-link/egl-symbols.txt"
test "$(wc -l < "$out/mali-link/gles-symbols.txt")" -gt 50
test "$(wc -l < "$out/mali-link/egl-symbols.txt")" -gt 10
awk '{print "void " $1 "(void) {}"}' "$out/mali-link/gles-symbols.txt" > "$out/mali-link/gles-stub.c"
awk '{print "void " $1 "(void) {}"}' "$out/mali-link/egl-symbols.txt" > "$out/mali-link/egl-stub.c"
aarch64-linux-gnu-gcc -shared -nostdlib -fPIC -Wl,-soname,libmali.so.0 \
    "$out/mali-link/gles-stub.c" -o "$out/mali-link/libGLESv2.so"
# EGL is a separate standard SONAME on Linux firmware: SDL2 loads
# libEGL.so.1 itself, so we require the same from the device. Keeping EGL on
# its own SONAME also avoids the linker deduplicating two stubs that both
# claimed libmali.so.0 (which silently dropped the EGL symbols).
aarch64-linux-gnu-gcc -shared -nostdlib -fPIC -Wl,-soname,libEGL.so.1 \
    "$out/mali-link/egl-stub.c" -o "$out/mali-link/libEGL.so"

# Provenance for BUILDING.md; package scripts publish only hashes, never libs.
{
    echo "generated by scripts/cross_prepare.sh from image: $CROSS_IMAGE_ID"
    echo "aarch64-linux-gnu-gcc: $(aarch64-linux-gnu-gcc --version | head -n1)"
    for pkg in libc6-dev-arm64-cross libsdl2-dev:arm64 libsdl2-ttf-dev:arm64 libgles2-mesa-dev:arm64 libegl-dev:arm64; do
        echo "$pkg: $(dpkg-query -W -f='${Version}' "$pkg" 2>/dev/null || echo unknown)"
    done
    echo "SDL2 runtime baseline: $(pkg-config --modversion sdl2 2>/dev/null || echo unknown)"
    echo "SDL2 link SONAME: $(aarch64-linux-gnu-readelf -d "$out/lib/libSDL2.so" | sed -n 's/.*SONAME.*\[\(.*\)\]/\1/p')"
    echo "Mali GLES stub SONAME: $(aarch64-linux-gnu-readelf -d "$out/mali-link/libGLESv2.so" | sed -n 's/.*SONAME.*\[\(.*\)\]/\1/p')"
    echo "EGL stub SONAME: $(aarch64-linux-gnu-readelf -d "$out/mali-link/libEGL.so" | sed -n 's/.*SONAME.*\[\(.*\)\]/\1/p')"
} > "$out/build-info.txt"
(cd "$out" && sha256sum include/SDL2/*.h lib/*.so mali-link/libGLESv2.so mali-link/libEGL.so > SHA256SUMS)
CONTAINER_EOF

image_id=$("$docker_bin" image inspect -f '{{.Id}}' "$image")
chmod +rx "$stage/prepare.sh"
"$docker_bin" run --rm --network none --read-only --tmpfs /tmp \
    --user "$(id -u):$(id -g)" \
    -e CROSS_IMAGE_ID="$image_id" \
    -v "$out:/out:rw" -v "$stage/prepare.sh:/prepare.sh:ro" \
    "$image" bash /prepare.sh

echo "Cross toolchain ready:"
echo "  image:   $image ($image_id)"
echo "  headers: third_party/target-libs/include/SDL2"
echo "  link:    third_party/target-libs/lib"
echo "  mali:    third_party/target-libs/mali-link (link-only, SONAME libmali.so.0)"
echo "Next: bash scripts/build_target.sh"
